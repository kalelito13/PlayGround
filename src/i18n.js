let current = 'es'
try {
  const saved = localStorage.getItem(LANG_KEY)
  if (SUPPORTED.includes(saved)) current = saved
} catch {}

export function getLang() { return current }
export function setLang(lang) {
  if (!SUPPORTED.includes(lang)) return current
  current = lang
  try { localStorage.setItem(LANG_KEY, lang) } catch {}
  document.documentElement.lang = lang
  window.dispatchEvent(new CustomEvent('nexo:lang', { detail: { lang } }))
  return current
}
export function toggleLang() { return setLang(current === 'es' ? 'en' : 'es') }
export function otherLang() { return current === 'es' ? 'en' : 'es' }
export function t(key, vars = {}) {
  let value = STRINGS[current]?.[key] ?? STRINGS.es[key] ?? key
  for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v))
  return value
}
export function elementName(el) { return current === 'en' ? (ELEMENT_EN[el] || el) : (ELEMENTS[el]?.name || el) }
export function rarityName(r) { return current === 'en' ? (RARITY_EN[r] || r) : (RARITIES[r]?.name || r) }
export function weatherName(w) { return current === 'en' ? (WEATHER_EN[w]?.[0] || w) : (WEATHERS[w]?.name || w) }
export function weatherDesc(w) { return current === 'en' ? (WEATHER_EN[w]?.[1] || '') : (WEATHERS[w]?.desc || '') }
export function localizedChapter(chapter) {
  if (!chapter) return null
  if (current === 'en' && CHAPTER_EN[chapter.id]) return { ...chapter, ...CHAPTER_EN[chapter.id] }
  return chapter
}
export function localizedSideQuest(q) {
  if (!q) return null
  if (current === 'en' && SIDE_EN[q.id]) return { ...q, ...SIDE_EN[q.id] }
  return q
}
export function localizedSideQuestById(id) { return localizedSideQuest(SIDEQUEST_BY_ID[id]) }
export function chapterTitle(id) { return localizedChapter(CHAPTERS[id])?.title || '' }
