for (const lang of Object.keys(EXTRA)) Object.assign(DICT[lang], EXTRA[lang]);

let current = 'es';

export function getLang() {
  return current;
}

export function languageInfo(id = current) {
  return LANGUAGES.find((l) => l.id === id) || LANGUAGES[0];
}

export function t(key, vars = {}, fallback = '') {
  const table = DICT[current] || DICT.en;
  let value = table[key] ?? DICT.en[key] ?? fallback ?? key;
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
}

export function applyI18n(root = document) {
  document.documentElement.lang = current;
  document.title = t('meta.title');
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-lang]').forEach((btn) => {
    const active = btn.dataset.lang === current;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', String(active));
  });
}

export function setLang(id) {
  if (!DICT[id]) return;
  current = id;
  try { localStorage.setItem('lumen-lang', id); } catch { /* storage may be blocked */ }
  applyI18n();
  document.dispatchEvent(new CustomEvent('lumen-lang', { detail: id }));
}

export function initI18n() {
  let saved = null;
  try { saved = localStorage.getItem('lumen-lang'); } catch { /* ignore */ }
  const browser = (navigator.language || 'en').slice(0, 2);
  const pick = DICT[saved] ? saved : DICT[browser] ? browser : 'es';
  current = pick;

  document.addEventListener('click', (event) => {
    const btn = event.target.closest('[data-lang]');
    if (!btn) return;
    setLang(btn.dataset.lang);
  });

  applyI18n();
}
